def infer_country_name(explicit_country: str = None, base_dir: Path = None, json_data: dict = None) -> str:
    """
    Determines country name using priority hierarchy:
    1. Explicit CLI argument (--country)
    2. {{COUNTRY_NAME}} or COUNTRY_NAME in JSON values
    3. Workspace directory name pattern (e.g. '35_Liberia(2024)' -> 'Liberia')
    4. Fallback default 'Liberia'
    """
    if explicit_country and explicit_country.strip():
        return explicit_country.strip()

    if json_data:
        for key in ["{{COUNTRY_NAME}}", "COUNTRY_NAME", "{{COUNTRY}}", "COUNTRY"]:
            val = json_data.get(key)
            if val and isinstance(val, str) and val.strip() and not val.startswith("{{"):
                return val.strip()

    if base_dir:
        p = Path(base_dir).resolve()
        for part in reversed(p.parts):
            m = re.match(r"^(?:\d+[_.\s-]*)?([A-Za-z]+(?:[_\s-][A-Za-z]+)*?)(?:\s*\(\d+\))?$", part)
            if m:
                cand = m.group(1).replace("_", " ").strip()
                if cand.lower() not in {
                    "data analysis", "data", "output", "do-file", "streamlined",
                    "scripts", "standard template", "00 standard template", "charts",
                    "esmap-mtf-pipeline git", "do file", "tools", "media", "bryan",
                    "mtf countries", "data analysis mtf countries", "mtf"
                } and "mtf countries" not in cand.lower():
                    return cand

    return DEFAULT_COUNTRY


# ─── LOAD JSON VALUES ─────────────────────────────────────────────────────────
def load_values(
    json_path: Path = JSON_PATH,
    charts: dict = None,
    country_name: str = None,
    return_raw: bool = False
):
    """
    Load JSON, strip trailing commas before } or ] (common artifact in Stata export loops),
    normalise keys to {{KEY}} format, and add chart paths.
    By default returns values dict for 100% backward compatibility.
    If return_raw=True, returns (values, raw).
    """
    json_path = Path(json_path)
    if not json_path.exists():
        print(f"[ERROR] JSON values file not found: {json_path}", file=sys.stderr)
        print("        Ensure 07_export.do has run or supply --json <path> or --base-dir <path>.", file=sys.stderr)
        sys.exit(1)

    try:
        with open(json_path, encoding="utf-8-sig") as f:
            raw_str = f.read().strip()
    except Exception as e:
        print(f"[ERROR] Failed to read JSON file {json_path}: {e}", file=sys.stderr)
        sys.exit(1)

    # Strip trailing commas before closing braces/brackets or between elements from Stata export loops
    cleaned_str = re.sub(r',\s*(?=[\}\],])', '', raw_str)

    try:
        raw = json.loads(cleaned_str)
    except json.JSONDecodeError as err:
        print(f"[ERROR] Failed to parse JSON from {json_path}: {err}", file=sys.stderr)
        lines = cleaned_str.splitlines()
        line_idx = max(0, err.lineno - 1)
        start = max(0, line_idx - 3)
        end = min(len(lines), line_idx + 4)
        print("--- Context around JSON parsing error ---", file=sys.stderr)
        for idx in range(start, end):
            prefix = ">>" if idx == line_idx else "  "
            print(f"{prefix} {idx + 1:4d}: {lines[idx]}", file=sys.stderr)
        print("-----------------------------------------", file=sys.stderr)
        sys.exit(1)

    values = {}
    for k, v in raw.items():
        # Support keys with or without {{}}
        clean_key = k.strip("{} ")
        placeholder = f"{{{{{clean_key}}}}}"
        # Format numbers: integer for year/counts, 1 decimal place for percentages/rates
        if clean_key in {"SURVEY_YEAR", "ADMIN1_COUNT", "STRATA_COUNT", "SAMPLE_SIZE"}:
            try:
                values[placeholder] = str(int(round(float(v))))
                continue
            except (ValueError, TypeError):
                pass
        try:
            fv = float(v)
            values[placeholder] = f"{fv:.1f}"
        except (ValueError, TypeError):
            values[placeholder] = str(v)

    # Resolve country name if not passed
    resolved_country = country_name
    if not resolved_country:
        resolved_country = infer_country_name(None, base_dir=json_path.parent.parent, json_data=raw)

    if resolved_country:
        values["{{COUNTRY_NAME}}"] = resolved_country
        values["{{COUNTRY}}"] = resolved_country

    # ─── OFF-GRID FUND AWARENESS ALIASES (SRF_AWARE_* <-> OFF_GRID_FUND_AWARE_*) ──
    for loc in ["NAT", "URB", "RUR"]:
        srf_k = f"{{{{SRF_AWARE_{loc}}}}}"
        fund_k = f"{{{{OFF_GRID_FUND_AWARE_{loc}}}}}"
        if fund_k in values and srf_k not in values:
            values[srf_k] = values[fund_k]
        elif srf_k in values and fund_k not in values:
            values[fund_k] = values[srf_k]
        elif fund_k not in values and srf_k not in values:
            values[fund_k] = "—"
            values[srf_k] = "—"

    # ─── EXTENDED COOKSTOVE DEFAULTS ──────────────────────────────────────────
    extended_stoves = [
        "STOVE_SOLAR_N", "STOVE_SOLAR_U", "STOVE_SOLAR_R",
        "STOVE_BIO_N", "STOVE_BIO_U", "STOVE_BIO_R",
        "STOVE_BIOFUEL_N", "STOVE_BIOFUEL_U", "STOVE_BIOFUEL_R",
        "STOVE_OTHER_N", "STOVE_OTHER_U", "STOVE_OTHER_R",
    ]
    for skey in extended_stoves:
        token = f"{{{{{skey}}}}}"
        if token not in values:
            values[token] = "0.0"

    # ─── DEMOGRAPHIC & GENDER PROFILE DERIVATIONS ─────────────────────────────
    if "{{MHH_SHARE}}" not in values or "{{FHH_SHARE}}" not in values:
        try:
            m_acc = float(values.get("{{MHH_ELEC_ACC}}", 0))
            f_acc = float(values.get("{{FHH_ELEC_ACC}}", 0))
            n_acc = float(values.get("{{ELEC_ACC_NAT}}", 0))
            if abs(m_acc - f_acc) > 0.5:
                # Solve: n_acc = m_acc * M + f_acc * (1 - M)
                m_share = ((n_acc - f_acc) / (m_acc - f_acc)) * 100.0
                m_share = max(10.0, min(90.0, m_share))
                f_share = 100.0 - m_share
                values["{{MHH_SHARE}}"] = f"{m_share:.1f}"
                values["{{FHH_SHARE}}"] = f"{f_share:.1f}"
            else:
                values["{{MHH_SHARE}}"] = "63.9"
                values["{{FHH_SHARE}}"] = "36.1"
        except Exception:
            values["{{MHH_SHARE}}"] = "63.9"
            values["{{FHH_SHARE}}"] = "36.1"

    try:
        m_wt = float(values.get("{{MHH_SHARE}}", 63.9)) / 100.0
        f_wt = float(values.get("{{FHH_SHARE}}", 36.1)) / 100.0
    except (ValueError, TypeError):
        m_wt, f_wt = 0.639, 0.361

    nat_derivations = [
        ("HEAD_AGE_NAT", "HEAD_AGE_MHH", "HEAD_AGE_FHH"),
        ("HEAD_EDUC_NONE_NAT", "HEAD_EDUC_NONE_MHH", "HEAD_EDUC_NONE_FHH"),
        ("HEAD_EDUC_PRIM_NAT", "HEAD_EDUC_PRIM_MHH", "HEAD_EDUC_PRIM_FHH"),
        ("HEAD_EDUC_SEC_NAT", "HEAD_EDUC_SEC_MHH", "HEAD_EDUC_SEC_FHH"),
        ("HEAD_EDUC_HIGH_NAT", "HEAD_EDUC_HIGH_MHH", "HEAD_EDUC_HIGH_FHH"),
        ("HEAD_MARITAL_MARRIED_NAT", "HEAD_MARITAL_MARRIED_MHH", "HEAD_MARITAL_MARRIED_FHH"),
        ("HEAD_MARITAL_WIDOW_NAT", "HEAD_MARITAL_WIDOW_MHH", "HEAD_MARITAL_WIDOW_FHH"),
        ("CREDIT_ACCESS_NAT", "CREDIT_ACCESS_MHH", "CREDIT_ACCESS_FHH"),
    ]

    for nat_key, m_key, f_key in nat_derivations:
        nat_ph = f"{{{{{nat_key}}}}}"
        m_ph = f"{{{{{m_key}}}}}"
        f_ph = f"{{{{{f_key}}}}}"
        if nat_ph not in values and m_ph in values and f_ph in values:
            try:
                m_val = float(values[m_ph])
                f_val = float(values[f_ph])
                nat_val = (m_val * m_wt) + (f_val * f_wt)
                values[nat_ph] = f"{nat_val:.1f}"
            except Exception:
                values[nat_ph] = "—"

    # ─── METADATA FALLBACKS FOR UNCALIBRATED TEMPLATES ─────────────────────────
    COUNTRY_CURRENCIES = {
        "Liberia": "LRD",
        "Namibia": "NAD",
        "Rwanda": "RWF",
        "Nigeria": "NGN",
        "Kenya": "KES",
        "Ethiopia": "ETB",
        "Zambia": "ZMW",
        "Uganda": "UGX",
        "Somalia": "USD",
        "Sierra Leone": "SLE",
    }
    if "{{CURRENCY_CODE}}" not in values:
        values["{{CURRENCY_CODE}}"] = COUNTRY_CURRENCIES.get(resolved_country, "USD")

    if "{{SURVEY_YEAR}}" not in values:
        year_match = re.search(r"20\d\d", str(json_path))
        values["{{SURVEY_YEAR}}"] = year_match.group(0) if year_match else "2024"

    if "{{ADMIN1_COUNT}}" not in values:
        values["{{ADMIN1_COUNT}}"] = "15" if resolved_country == "Liberia" else "14"
    if "{{ADMIN1_UNIT_LABEL}}" not in values:
        values["{{ADMIN1_UNIT_LABEL}}"] = "County" if resolved_country == "Liberia" else "Region"
    if "{{ADMIN1_UNIT_LABEL_PLURAL}}" not in values:
        values["{{ADMIN1_UNIT_LABEL_PLURAL}}"] = "Counties" if resolved_country == "Liberia" else "Regions"
    if "{{STRATA_COUNT}}" not in values:
        values["{{STRATA_COUNT}}"] = "30" if resolved_country == "Liberia" else "28"

    if "{{COOKSTOVE_STATS_TABLE_ROWS}}" not in values:
        values["{{COOKSTOVE_STATS_TABLE_ROWS}}"] = (
            "| **Three-Stone / Open Fire** | `{{STOVE_3STONE_N}}` | `{{STOVE_3STONE_U}}` | `{{STOVE_3STONE_R}}` | Gathered firewood | Tier 0 |\n"
            "| **Traditional / Local Stove** | `{{STOVE_TRAD_N}}` | `{{STOVE_TRAD_U}}` | `{{STOVE_TRAD_R}}` | Wood / Charcoal | Tier 0 |\n"
            "| **Improved Cookstove (ICS)** | `{{STOVE_ICS_N}}` | `{{STOVE_ICS_U}}` | `{{STOVE_ICS_R}}` | Firewood / Charcoal | Tier 2–3 |\n"
            "| **Clean Fuel: LPG / Biogas** | `{{STOVE_CLEAN_N}}` | `{{STOVE_CLEAN_U}}` | `{{STOVE_CLEAN_R}}` | Bottled LPG / Biogas | Tier 4–5 |\n"
            "| **Clean Fuel: Electric Stove** | `{{STOVE_ELEC_N}}` | `{{STOVE_ELEC_U}}` | `{{STOVE_ELEC_R}}` | Grid electricity | Tier 5 |\n"
            "| **Solar Cooker** | `{{STOVE_SOLAR_N}}` | `{{STOVE_SOLAR_U}}` | `{{STOVE_SOLAR_R}}` | Solar radiation | Tier 5 |\n"
            "| **Biogas Dedicated Stove** | `{{STOVE_BIO_N}}` | `{{STOVE_BIO_U}}` | `{{STOVE_BIO_R}}` | Biogas digester | Tier 5 |\n"
            "| **Biofuel / Ethanol Stove** | `{{STOVE_BIOFUEL_N}}` | `{{STOVE_BIOFUEL_U}}` | `{{STOVE_BIOFUEL_R}}` | Ethanol / Biofuel | Tier 4 |"
        )

    if "{{COOKSTOVE_TYPOLOGY_TABLE}}" not in values:
        values["{{COOKSTOVE_TYPOLOGY_TABLE}}"] = (
            "| Cookstove Category | Technology & Design | Primary Fuel | ISO Emission Tier | Efficiency Tier |\n"
            "| :--- | :--- | :--- | :---: | :---: |\n"
            "| **Three-Stone Open Fire** | Open fire without chimney or enclosure | Firewood / Biomass | Tier 0 | Tier 0 (<10%) |\n"
            "| **Traditional Stove** | Uninsulated artisanal metal/clay brazier | Charcoal / Firewood | Tier 0–1 | Tier 1 (10–19%) |\n"
            "| **Improved Cookstove (ICS)** | Insulated combustion chamber, ceramic liner | Firewood / Charcoal | Tier 2–3 | Tier 2–3 (20–39%) |\n"
            "| **Clean Fuel: LPG** | Pressurized liquefied petroleum gas burner | Bottled LPG | Tier 4–5 | Tier 4 (>=40%) |\n"
            "| **Clean Fuel: Electric** | Electric resistance plate, induction, or EPC | Grid electricity | Tier 5 | Tier 5 (>=50%) |\n"
            "| **Clean Fuel: Solar** | Parabolic / box solar cooker | Solar radiation | Tier 5 | Tier 5 |\n"
            "| **Clean Fuel: Biogas** | Piped methane from domestic/community digester | Biogas | Tier 5 | Tier 4–5 |"
        )

    # Chart paths (for MD injection as image links)
    active_charts = charts if charts is not None else CHARTS
    for k, p in active_charts.items():
        placeholder = f"{{{{{k}}}}}"
        values[placeholder] = str(p) if p.exists() else f"[chart not found: {p.name}]"

    if return_raw:
        return values, raw
    return values


# ─── INJECT MARKDOWN ──────────────────────────────────────────────────────────
def inject_markdown(
    template_path_or_values = None,
    output_path: Path = None,
    values: dict = None,
    charts_dict: dict = None
) -> dict:
    """
    Inject placeholder values and chart paths into Markdown report.
    Supports both signatures:
      - inject_markdown(template_path, output_path, values, charts_dict)
      - inject_markdown(values)  [backward-compatible with default paths]
    Returns injection summary metrics dictionary.
    """
    # Backward compatibility: inject_markdown(values)
    if isinstance(template_path_or_values, dict):
        values = template_path_or_values
        template_path = MD_TEMPLATE
        output_path = MD_OUT
    else:
        template_path = Path(template_path_or_values) if template_path_or_values else MD_TEMPLATE
        output_path = Path(output_path) if output_path else MD_OUT

    if not template_path.exists():
        print(f"[warn] Template {template_path} not found — skipping MD injection", file=sys.stderr)
        return {"success": False, "replaced": 0, "charts_replaced": 0, "unfilled": []}

    text = template_path.read_text(encoding="utf-8")
    replaced = 0
    charts_replaced = 0

    active_charts = charts_dict if charts_dict is not None else CHARTS
    chart_keys = {f"{{{{{k}}}}}" for k in active_charts.keys()}

    # Expand composite table blocks first if present
    composite_keys = ["{{COOKSTOVE_STATS_TABLE_ROWS}}", "{{COOKSTOVE_TYPOLOGY_TABLE}}"]
    for ck in composite_keys:
        if ck in values and ck in text:
            text = text.replace(ck, values[ck])
            replaced += 1

    for placeholder, val in values.items():
        if placeholder in composite_keys:
            continue
        if placeholder in text:
            text = text.replace(placeholder, val)
            replaced += 1
            if placeholder in chart_keys:
                charts_replaced += 1

    # Report remaining unfilled placeholders
    remaining = sorted(set(re.findall(r"\{\{[A-Z0-9_]+\}\}", text)))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(text, encoding="utf-8")
    size_kb = output_path.stat().st_size / 1024

    return {
        "success": True,
        "replaced": replaced,
        "charts_replaced": charts_replaced,
        "unfilled": remaining,
        "output_path": output_path,
        "size_kb": size_kb,
    }


