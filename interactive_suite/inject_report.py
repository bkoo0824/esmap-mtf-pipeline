    # FIG 02: Source Mix (11_electricity_source_mix.png)
    # ─────────────────────────────────────────────────────────────────────────
    ws = wb.create_sheet(title="Fig02_Source_Mix")
    ws.views.sheetView[0].showGridLines = True
