# ─── INJECT MARKDOWN ──────────────────────────────────────────────────────────
def inject_markdown(
    template_path_or_values = None,
    output_path: Path = None,
    values: dict = None,
    charts_dict: dict = None
) -> dict:
    """
    Inject placeholder values and chart paths into Markdown report.
    Supports both signatures:
      - inject_markdown(template_path, output_path, values, charts_dict)
      - inject_markdown(values)  [backward-compatible with default paths]
    Returns injection summary metrics dictionary.
    """
    # Backward compatibility: inject_markdown(values)
    if isinstance(template_path_or_values, dict):
        values = template_path_or_values
        template_path = MD_TEMPLATE
        output_path = MD_OUT
    else:
        template_path = Path(template_path_or_values) if template_path_or_values else MD_TEMPLATE
        output_path = Path(output_path) if output_path else MD_OUT

    if not template_path.exists():
        print(f"[warn] Template {template_path} not found — skipping MD injection", file=sys.stderr)
        return {"success": False, "replaced": 0, "charts_replaced": 0, "unfilled": []}

    text = template_path.read_text(encoding="utf-8")
    replaced = 0
    charts_replaced = 0

    active_charts = charts_dict if charts_dict is not None else CHARTS
    chart_keys = {f"{{{{{k}}}}}" for k in active_charts.keys()}

    # Expand composite table blocks first if present
    composite_keys = ["{{COOKSTOVE_STATS_TABLE_ROWS}}", "{{COOKSTOVE_TYPOLOGY_TABLE}}"]
    for ck in composite_keys:
        if ck in values and ck in text:
            text = text.replace(ck, values[ck])
            replaced += 1

    # When off-grid fund awareness was not surveyed in a country (marked as "—" or missing):
    if values.get("{{OFF_GRID_FUND_AWARE_NAT}}") in ["—", "", None]:
        text = text.replace(
            "Public awareness of government off-grid financing mechanisms is recorded at `{{OFF_GRID_FUND_AWARE_NAT}}%` nationwide (`{{OFF_GRID_FUND_AWARE_URB}}%` in urban areas and `{{OFF_GRID_FUND_AWARE_RUR}}%` in rural areas).",
            "Public awareness of dedicated government off-grid financing facilities was not explicitly measured in the survey, though field observations indicate that consumer familiarity with formal credit windows and quality standards remains low in remote rural settlements."
        )
        text = text.replace(
            "* **Expand Public Awareness:** Address the `{{OFF_GRID_FUND_AWARE_NAT}}%` national awareness rate of off-grid financing mechanisms through targeted community outreach and local radio campaigns.",
            "* **Expand Public Awareness:** Conduct targeted community outreach, demonstration campaigns, and local awareness drives to inform rural consumers about quality-certified solar products and flexible financing mechanisms."
        )

    for placeholder, val in values.items():
        if placeholder in composite_keys:
            continue
        if placeholder in text:
            text = text.replace(placeholder, val)
            replaced += 1
            if placeholder in chart_keys:
                charts_replaced += 1

    # Report remaining unfilled placeholders
    remaining = sorted(set(re.findall(r"\{\{[A-Z0-9_]+\}\}", text)))

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(text, encoding="utf-8")
    size_kb = output_path.stat().st_size / 1024

    return {
        "success": True,
        "replaced": replaced,
        "charts_replaced": charts_replaced,
        "unfilled": remaining,
        "output_path": output_path,
        "size_kb": size_kb,
    }


