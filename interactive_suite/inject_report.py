def _set_cell_margins(cell, top=100, bottom=100, left=150, right=150):
    """Set inner padding for a table cell in twips."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcMar = OxmlElement('w:tcMar')
    for m, val in [('top', top), ('bottom', bottom), ('left', left), ('right', right)]:
        node = OxmlElement(f'w:{m}')
        node.set(qn('w:w'), str(val))
        node.set(qn('w:type'), 'dxa')
        tcMar.append(node)
    tcPr.append(tcMar)


def _set_cell_shading(cell, color_hex):
    """Set background color of a cell."""
    shd = parse_xml(f'<w:shd {nsdecls("w")} w:fill="{color_hex}"/>')
    cell._tc.get_or_add_tcPr().append(shd)


def _set_callout_borders(cell, border_color_hex=HEX_NAVY, border_size=24):
    """Left thick border, no other borders for callout box."""
    tcPr = cell._tc.get_or_add_tcPr()
    tcBorders = OxmlElement('w:tcBorders')
    left = OxmlElement('w:left')
    left.set(qn('w:val'), 'single')
    left.set(qn('w:sz'), str(border_size))
    left.set(qn('w:space'), '0')
    left.set(qn('w:color'), border_color_hex)
    tcBorders.append(left)
    for side in ['top', 'bottom', 'right']:
        b = OxmlElement(f'w:{side}')
        b.set(qn('w:val'), 'none')
        tcBorders.append(b)
    tcPr.append(tcBorders)


def _set_table_borders(table, border_color_hex=HEX_BORDER):
    """Set clean borders on a table."""
    tblPr = table._tbl.tblPr
    borders = parse_xml(
        f'<w:tblBorders {nsdecls("w")}>'
        f'  <w:top w:val="single" w:sz="4" w:space="0" w:color="{border_color_hex}"/>'
        f'  <w:bottom w:val="single" w:sz="6" w:space="0" w:color="{HEX_NAVY}"/>'
        f'  <w:left w:val="none"/>'
        f'  <w:right w:val="none"/>'
        f'  <w:insideH w:val="single" w:sz="4" w:space="0" w:color="{border_color_hex}"/>'
        f'  <w:insideV w:val="none"/>'
        f'</w:tblBorders>'
    )
    tblPr.append(borders)


def _add_formatted_runs(paragraph, text, base_color=None, base_size=None):
    """Parse inline **bold**, *italic*, and `code` into formatted Word runs."""
    if not HAS_DOCX:
        return
    if base_color is None:
        base_color = COLOR_CHARCOAL
    if base_size is None:
        base_size = Pt(10.0)
    tokens = re.split(r'(\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`)', text)
    for token in tokens:
        if not token:
            continue
        if token.startswith('**') and token.endswith('**'):
            run = paragraph.add_run(token[2:-2])
            run.bold = True
            run.font.color.rgb = base_color
            run.font.size = base_size
        elif token.startswith('*') and token.endswith('*'):
            run = paragraph.add_run(token[1:-1])
            run.italic = True
            run.font.color.rgb = base_color
            run.font.size = base_size
        elif token.startswith('`') and token.endswith('`'):
            run = paragraph.add_run(token[1:-1])
            run.bold = True
            run.font.name = 'Consolas'
            run.font.color.rgb = COLOR_NAVY
            run.font.size = Pt(base_size.pt - 0.5)
        else:
            run = paragraph.add_run(token)
            run.font.color.rgb = base_color
            run.font.size = base_size


def inject_docx_from_markdown(
    md_path: Path,
    docx_path: Path,
    country_name: str = "Liberia",
    base_dir: Path = None,
    charts_dir: Path = None
) -> bool:
    """
    Renders the fully injected Markdown report directly into a publication-grade Word document (.docx).
    Uses dynamic country headers/footers and ESMAP styling guidelines.
    """
    if not HAS_DOCX:
        print("  [info] python-docx is not installed — Word report skipped.")
        print("         To generate Word reports (.docx), install via: pip install python-docx pillow")
        return False

    doc = Document()

    # Set default document typography: Calibri, 10 pt, charcoal
    try:
        style_normal = doc.styles['Normal']
        style_normal.font.name = 'Calibri'
        style_normal.font.size = Pt(10.0)
        style_normal.font.color.rgb = COLOR_CHARCOAL
    except Exception:
        pass

    # 1-inch margins
    for section in doc.sections:
        section.top_margin = Inches(1.0)
        section.bottom_margin = Inches(1.0)
        section.left_margin = Inches(1.0)
        section.right_margin = Inches(1.0)
        section.different_first_page_header_footer = True

        # Header / Footer with dynamic country name
        header = section.header
        hp = header.paragraphs[0]
        hp.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        hrun = hp.add_run(f"ESMAP | Beyond Connections: {country_name} Energy Access Diagnostic Report")
        hrun.font.size = Pt(8.5)
        hrun.font.color.rgb = COLOR_MUTED

        footer = section.footer
        fp = footer.paragraphs[0]
        fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        frun = fp.add_run(f"Multi-Tier Framework (MTF) Household Survey — {country_name}")
        frun.font.size = Pt(8.5)
        frun.font.color.rgb = COLOR_MUTED

    md_content = md_path.read_text(encoding='utf-8')
    lines = md_content.splitlines()

    i = 0
    n = len(lines)

    while i < n:
        line = lines[i].strip()

        if not line:
            i += 1
            continue

        # Skip HTML comments (both single-line and multi-line <!-- ... -->)
        if line.startswith('<!--'):
            if '-->' in line:
                i += 1
                continue
            while i < n and '-->' not in lines[i]:
                i += 1
            if i < n:
                i += 1
            continue

        if line in ['---', '***', '___']:
            i += 1
            continue

        # Images: ![caption](path) or ![caption](<path>) or ![caption](path "title")
        img_match = re.match(r'^!\[(.*?)\]\s*\((.+)\)$', line)
        if img_match:
            caption = img_match.group(1).strip()
            raw_target = img_match.group(2).strip()

            # Strip optional angle brackets: <path/to/img.png>
            if raw_target.startswith('<') and raw_target.endswith('>'):
                raw_target = raw_target[1:-1].strip()

            # Handle optional Markdown title: path "Optional Title"
            title_m = re.match(r'^(.*?)\s+["\'](.*)["\']$', raw_target)
            if title_m:
                img_path_str = title_m.group(1).strip()
                if not caption:
                    caption = title_m.group(2).strip()
            else:
                img_path_str = raw_target

            # Multi-candidate path resolution
            img_path = Path(img_path_str)
            if not img_path.exists():
                candidates = [
                    md_path.parent / img_path_str,
                    base_dir / img_path_str.lstrip('/') if base_dir else None,
                    charts_dir / Path(img_path_str).name if charts_dir else None,
                    md_path.parent / "charts" / Path(img_path_str).name,
                    base_dir / "Output" / "charts" / Path(img_path_str).name if base_dir else None,
                    base_dir / "Output" / "streamlined" / "charts" / Path(img_path_str).name if base_dir else None,
                ]
                for cand in candidates:
                    if cand and cand.exists():
                        img_path = cand
                        break

            if img_path.exists() and img_path.is_file():
                try:
                    p_img = doc.add_paragraph()
                    p_img.alignment = WD_ALIGN_PARAGRAPH.CENTER
                    p_img.paragraph_format.space_before = Pt(12)
                    p_img.paragraph_format.space_after = Pt(4)
                    p_img.add_run().add_picture(str(img_path), width=Inches(5.6))

                    if caption:
                        p_cap = doc.add_paragraph()
                        p_cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
                        p_cap.paragraph_format.space_before = Pt(2)
                        p_cap.paragraph_format.space_after = Pt(14)
                        c_run = p_cap.add_run(caption)
                        c_run.italic = True
                        c_run.font.size = Pt(9.5)
                        c_run.font.color.rgb = COLOR_MUTED
                except Exception as e:
                    print(f"  [warn] Failed to insert picture {img_path}: {e}", file=sys.stderr)
                    p_err = doc.add_paragraph(f"[Image insertion error: {img_path.name} — {e}]")
                    p_err.runs[0].font.color.rgb = RGBColor(200, 0, 0)
            else:
                p_err = doc.add_paragraph(f"[Image not found: {img_path_str}]")
                p_err.runs[0].font.color.rgb = RGBColor(200, 0, 0)
            i += 1
            continue

        # Headings
        if line.startswith('# '):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(18)
            p.paragraph_format.space_after = Pt(6)
            run = p.add_run(line[2:].strip())
            run.bold = True
            run.font.size = Pt(22)
            run.font.color.rgb = COLOR_NAVY
            i += 1
            continue

        if line.startswith('## '):
            h_text = line[3:].strip()
            if h_text.startswith('CHAPTER') or h_text in ['EXECUTIVE SUMMARY', 'ACKNOWLEDGMENTS']:
                doc.add_page_break()
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(16)
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.keep_with_next = True
            run = p.add_run(h_text)
            run.bold = True
            run.font.size = Pt(15)
            run.font.color.rgb = COLOR_NAVY
            i += 1
            continue

        if line.startswith('### '):
            h_text = line[4:].strip()
            # Box Callout
            if h_text.startswith('Box '):
                box_title = h_text
                i += 1
                box_content = []
                while i < n and lines[i].strip() and not lines[i].strip().startswith('#') and not lines[i].strip().startswith('---'):
                    box_content.append(lines[i].strip())
                    i += 1

                tbl = doc.add_table(rows=1, cols=1)
                tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
                cell = tbl.cell(0, 0)
                cell.width = Inches(6.5)
                _set_cell_margins(cell, top=140, bottom=140, left=180, right=160)
                _set_cell_shading(cell, HEX_LIGHT_BG)
                _set_callout_borders(cell, border_color_hex=HEX_NAVY, border_size=28)

                cp = cell.paragraphs[0]
                cp.paragraph_format.space_before = Pt(2)
                cp.paragraph_format.space_after = Pt(4)
                bt_run = cp.add_run(box_title)
                bt_run.bold = True
                bt_run.font.size = Pt(11)
                bt_run.font.color.rgb = COLOR_NAVY

                for b_line in box_content:
                    bp = cell.add_paragraph()
                    bp.paragraph_format.space_before = Pt(2)
                    bp.paragraph_format.space_after = Pt(3)
                    if b_line.startswith('* ') or b_line.startswith('- '):
                        _add_formatted_runs(bp, "•  " + b_line[2:], base_color=COLOR_CHARCOAL, base_size=Pt(9.5))
                    else:
                        _add_formatted_runs(bp, b_line, base_color=COLOR_CHARCOAL, base_size=Pt(9.5))

                sp = doc.add_paragraph()
                sp.paragraph_format.space_before = Pt(0)
                sp.paragraph_format.space_after = Pt(6)
                continue

            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(12)
            p.paragraph_format.space_after = Pt(4)
            p.paragraph_format.keep_with_next = True
            run = p.add_run(h_text)
            run.bold = True
            run.font.size = Pt(12.5)
            run.font.color.rgb = COLOR_ACCENT
            i += 1
            continue

        if line.startswith('#### '):
            p = doc.add_paragraph()
            p.paragraph_format.space_before = Pt(10)
            p.paragraph_format.space_after = Pt(3)
            p.paragraph_format.keep_with_next = True
            run = p.add_run(line[5:].strip())
            run.bold = True
            run.font.size = Pt(11)
            run.font.color.rgb = COLOR_CHARCOAL
            i += 1
            continue

        # Tables: line starts with '|'
        if line.startswith('|') and '|' in line[1:]:
            table_lines = []
            while i < n and lines[i].strip().startswith('|'):
                table_lines.append(lines[i].strip())
                i += 1

            if len(table_lines) >= 2:
                header_cells = [c.strip() for c in table_lines[0].strip('|').split('|')]
                data_rows = []
                for t_line in table_lines[2:]:
                    cells = [c.strip() for c in t_line.strip('|').split('|')]
                    while len(cells) < len(header_cells):
                        cells.append("")
                    data_rows.append(cells[:len(header_cells)])

                tbl = doc.add_table(rows=len(data_rows) + 1, cols=len(header_cells))
                tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
                _set_table_borders(tbl)

                # Header
                hdr_row = tbl.rows[0]
                trPr = hdr_row._tr.get_or_add_trPr()
                trPr.append(parse_xml(f'<w:tblHeader {nsdecls("w")}/>'))

                for c_idx, text in enumerate(header_cells):
                    cell = hdr_row.cells[c_idx]
                    _set_cell_margins(cell, top=100, bottom=100, left=120, right=120)
                    _set_cell_shading(cell, HEX_NAVY)
                    p = cell.paragraphs[0]
                    p.paragraph_format.space_before = Pt(0)
                    p.paragraph_format.space_after = Pt(0)
                    p.alignment = WD_ALIGN_PARAGRAPH.CENTER if c_idx > 0 else WD_ALIGN_PARAGRAPH.LEFT
                    _add_formatted_runs(p, text, base_color=COLOR_WHITE, base_size=Pt(9.5))
                    for run in p.runs:
                        run.bold = True

                # Data Rows
                for r_idx, row_data in enumerate(data_rows):
                    row = tbl.rows[r_idx + 1]
                    bg_color = HEX_ALT_ROW if r_idx % 2 == 1 else "FFFFFF"
                    for c_idx, val in enumerate(row_data):
                        cell = row.cells[c_idx]
                        _set_cell_margins(cell, top=80, bottom=80, left=120, right=120)
                        if bg_color != "FFFFFF":
                            _set_cell_shading(cell, bg_color)
                        p = cell.paragraphs[0]
                        p.paragraph_format.space_before = Pt(0)
                        p.paragraph_format.space_after = Pt(0)
                        if re.match(r'^-?\d+(\.\d+)?%?$', val) or val in ['—', '-', 'N/A']:
                            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
                        else:
                            p.alignment = WD_ALIGN_PARAGRAPH.LEFT
                        _add_formatted_runs(p, val, base_color=COLOR_CHARCOAL, base_size=Pt(9.0))

                sp = doc.add_paragraph()
                sp.paragraph_format.space_before = Pt(0)
                sp.paragraph_format.space_after = Pt(8)
            continue

        # Bullet list
        if line.startswith('* ') or line.startswith('- '):
            p = doc.add_paragraph(style='List Bullet')
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(3)
            _add_formatted_runs(p, line[2:].strip(), base_color=COLOR_CHARCOAL, base_size=Pt(10.0))
            i += 1
            continue

        # Numbered list
        num_match = re.match(r'^(\d+)\.\s+(.*)', line)
        if num_match:
            p = doc.add_paragraph()
            p.paragraph_format.left_indent = Inches(0.25)
            p.paragraph_format.first_line_indent = Inches(-0.25)
            p.paragraph_format.space_before = Pt(1)
            p.paragraph_format.space_after = Pt(3)
            r_num = p.add_run(f"{num_match.group(1)}. ")
            r_num.bold = True
            r_num.font.color.rgb = COLOR_NAVY
            r_num.font.size = Pt(10.0)
            _add_formatted_runs(p, num_match.group(2).strip(), base_color=COLOR_CHARCOAL, base_size=Pt(10.0))
            i += 1
            continue

        # Regular paragraph
        p = doc.add_paragraph()
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(5)
        p.paragraph_format.line_spacing = 1.15

        # Math display $$...$$
        if line.startswith('$$') and line.endswith('$$'):
            math_text = line.strip('$').strip()
            clean_math = math_text.replace(r'\text{', '').replace('}', '').replace(r'\min', 'min')
            p.alignment = WD_ALIGN_PARAGRAPH.CENTER
            m_run = p.add_run(clean_math)
            m_run.italic = True
            m_run.bold = True
            m_run.font.size = Pt(11)
            m_run.font.color.rgb = COLOR_NAVY
        else:
            _add_formatted_runs(p, line, base_color=COLOR_CHARCOAL, base_size=Pt(10.0))

        i += 1

    try:
        docx_path.parent.mkdir(parents=True, exist_ok=True)
        doc.save(str(docx_path))
        size_kb = docx_path.stat().st_size / 1024
        print(f"  ✓ Word report: {docx_path.name} ({size_kb:.1f} KB)")
        return True
    except PermissionError:
        print(f"  [ERROR] Cannot save Word report: {docx_path.name} is open or locked by another process.", file=sys.stderr)
        return False
    except Exception as e:
        print(f"  [ERROR] Failed to save Word report {docx_path.name}: {e}", file=sys.stderr)
        return False


