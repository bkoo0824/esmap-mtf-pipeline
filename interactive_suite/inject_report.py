# ─── MAIN ─────────────────────────────────────────────────────────────────────
def main():
    parser = build_cli_parser()
    args = parser.parse_args()

    # 1. Resolve Base Directory
    base_dir = Path(args.base_dir).resolve() if args.base_dir else DEFAULT_BASE_DIR

    # 2. Resolve Output Directory
    if args.output_dir:
        output_dir = Path(args.output_dir).resolve()
    else:
        streamlined = base_dir / "Output" / "streamlined"
        output_dir = streamlined if streamlined.exists() else base_dir / "Output"
    try:
        output_dir.mkdir(parents=True, exist_ok=True)
    except OSError:
        pass

    # 3. Resolve JSON Path
    if args.json:
        json_path = Path(args.json).resolve()
    else:
        candidates = [
            output_dir / "mtf_report_values.json",
            base_dir / "Output" / "mtf_report_values.json",
            base_dir / "Output" / "streamlined" / "mtf_report_values.json",
            base_dir / "interactive_suite" / "Output" / "mtf_report_values.json",
        ]
        json_path = next((c for c in candidates if c.exists()), candidates[0])

    # 4. Resolve Template Path
    if args.template:
        template_path = Path(args.template).resolve()
    else:
        candidates = [
            DO_FILE_DIR / "MTF_Report_Template.md",
            base_dir / "Do-file" / "MTF_Report_Template.md",
            base_dir / "stata_pipeline" / "MTF_Report_Template.md",
            base_dir / "interactive_suite" / "MTF_Report_Template.md",
        ]
        template_path = next((c for c in candidates if c.exists()), candidates[0])

    # 5. Resolve Charts Directory
    if args.charts_dir:
        charts_dir = Path(args.charts_dir).resolve()
    else:
        candidates = [
            output_dir / "charts",
            base_dir / "Output" / "charts",
            base_dir / "Output" / "streamlined" / "charts",
            base_dir / "interactive_suite" / "Output" / "charts",
        ]
        charts_dir = next((c for c in candidates if c.exists()), candidates[0])

    # 6. Build Charts Dictionary
    charts_dict = get_charts_dict(charts_dir)
    found_charts = sum(1 for p in charts_dict.values() if p.exists())
    total_charts = len(charts_dict)

    # 7. Initial pass of JSON to discover country name if needed
    country = infer_country_name(args.country, base_dir)
    values, raw_json = load_values(json_path, charts=charts_dict, country_name=country, return_raw=True)
    # Refine country name if present in JSON
    if not args.country:
        country = infer_country_name(None, base_dir, raw_json)
        values["{{COUNTRY_NAME}}"] = country
        values["{{COUNTRY}}"] = country

    # 8. Dynamic File Naming
    country_file = country.replace(" ", "_")
    md_out = Path(args.output_md).resolve() if args.output_md else output_dir / f"MTF_{country_file}_Report.md"
    docx_out = Path(args.output_docx).resolve() if args.output_docx else output_dir / f"MTF_{country_file}_Report.docx"
    excel_out = Path(args.output_excel).resolve() if args.output_excel else output_dir / f"MTF_{country_file}_Report_Figures_Data.xlsx"

    # ─── LOG HEADER ───────────────────────────────────────────────────────────
    print("\n" + "=" * 76)
    print(f"  ESMAP MTF {country} — Automated Report & Graphics Data Pipeline")
    print("=" * 76)
    print(f"  Target Country:      {country}")
    print(f"  Base Directory:      {base_dir}")
    print(f"  Econometric JSON:    {json_path}")
    print(f"  Markdown Template:   {template_path}")
    print(f"  Charts Directory:    {charts_dir} ({found_charts}/{total_charts} images verified)")
    print(f"  Markdown Output:     {md_out}")
    print(f"  Word (.docx) Output: {docx_out}")
    print(f"  Designer Excel Pkg:  {excel_out}")
    print("-" * 76)

    # ─── STEP 1: INJECT MARKDOWN ──────────────────────────────────────────────
    print("\n[Step 1/3] Injecting Econometric Values & Charts into Markdown...")
    md_res = inject_markdown(template_path, md_out, values, charts_dict=charts_dict)

    if md_res.get("success"):
        print(f"  ✓ Markdown report generated: {md_out.name} ({md_res['size_kb']:.1f} KB)")
        print(f"  ✓ Total placeholders replaced: {md_res['replaced']}")
        print(f"  ✓ Chart figures injected:       {md_res['charts_replaced']} of {total_charts}")
        
        unfilled = md_res["unfilled"]
        if unfilled:
            unfilled_charts = [p for p in unfilled if p.startswith("{{CHART_")]
            unfilled_data = [p for p in unfilled if not p.startswith("{{CHART_")]
            print(f"  ⚠ Unfilled placeholders remaining ({len(unfilled)} total):")
            if unfilled_charts:
                print(f"    - Missing Charts ({len(unfilled_charts)}): {', '.join(unfilled_charts)}")
            if unfilled_data:
                preview = ', '.join(unfilled_data[:8])
                more_suffix = f" ... and {len(unfilled_data) - 8} more" if len(unfilled_data) > 8 else ""
                print(f"    - Unfilled Data Tokens ({len(unfilled_data)}): {preview}{more_suffix}")
        else:
            print("  ✓ Zero unfilled placeholders remaining — 100% template coverage!")
    else:
        print("  ✗ Markdown injection failed.", file=sys.stderr)
        print(f"  [FATAL] Template '{template_path}' could not be processed.", file=sys.stderr)
        print("          Aborting report generation before Word (.docx) rendering.", file=sys.stderr)
        sys.exit(1)

    # ─── STEP 2: RENDER WORD DOCUMENT ─────────────────────────────────────────
    print("\n[Step 2/3] Rendering Publication Word Document (.docx)...")
    docx_status = "Skipped"
    if HAS_DOCX and md_out.exists():
        ok = inject_docx_from_markdown(md_out, docx_out, country_name=country, base_dir=base_dir, charts_dir=charts_dir)
        docx_status = "Generated" if ok else "Failed"
    elif not HAS_DOCX:
        print("  [info] python-docx not installed — skipping Word (.docx) generation.")
        print("         Install via: pip install python-docx pillow")
        docx_status = "Skipped (python-docx not installed)"
    else:
        print(f"  [warn] Markdown file not found ({md_out}) — skipping Word generation.")
        docx_status = "Failed"

    # ─── STEP 3: EXPORT DESIGNER FIGURES DATA EXCEL PACKAGE ───────────────────
    print("\n[Step 3/3] Exporting Designer Figures Excel Data Package...")
    excel_status = "Skipped"
    if HAS_OPENPYXL:
        res_xl = build_designer_chart_data_excel(base_dir, output_dir, country_name=country, custom_excel_out=excel_out)
        excel_status = "Generated" if (res_xl and res_xl.exists()) else "Failed"
    else:
        print("  [info] openpyxl not installed — skipping Designer Figures Excel generation.")
        print("         Install via: pip install openpyxl")
        excel_status = "Skipped (openpyxl not installed)"

    # ─── COMPLETION SUMMARY ───────────────────────────────────────────────────
    print("\n" + "=" * 76)
    print("  Report & Graphics Package Generation Summary")
    print("=" * 76)
    print(f"  Country:          {country}")
    print(f"  Markdown Report:  {md_out} (Status: {'Generated' if md_out.exists() else 'Failed'})")
    print(f"  Word Document:    {docx_out} (Status: {docx_status})")
    print(f"  Designer Excel:   {excel_out} (Status: {excel_status})")
    print(f"  Charts Available: {found_charts}/{total_charts}")
    print("=" * 76 + "\n")


if __name__ == "__main__":
    main()
